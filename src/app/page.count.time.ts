// When the page count was made and when it is made again, worded for whoever reads it. No
// dependency: the server renders it in UTC, the browser again in the viewer's own time.

/** How long a count holds, in seconds: the home page's ISR and the cache of its fetches alike. */
export const REFRESH_SECONDS = 3600

/** Whose clock a time is read on: the viewer's when left out. */
interface Clock {
  locale?: string
  timeZone?: string
}

/** The calendar day of `date` on `clock`, to compare two dates by. */
function day(date: Date, { locale, timeZone }: Clock) {
  return date.toLocaleDateString(locale, { timeZone })
}

/**
 * `date` as a time of day, with its day too when it is not the one of `now`.
 *
 * @param date What to word.
 * @param now The day the reader is in.
 * @param clock Locale and time zone, the viewer's when left out.
 */
function formatTime(date: Date, now: Date, clock: Clock) {
  const { locale, timeZone } = clock
  const time = date.toLocaleTimeString(locale, { timeZone, timeStyle: 'short' })
  if (day(date, clock) === day(now, clock)) return time

  return `${date.toLocaleDateString(locale, { timeZone, month: 'short', day: 'numeric' })}, ${time}`
}

/**
 * When a count was made, and the time past which it is made again.
 *
 * "Past which", not "at which": the page is regenerated by the first visit after the hour, and
 * nobody may come by for a while. `next` is `undefined` once that time has gone -- the count is
 * then due, and the visit that saw it has already set one going.
 *
 * @param countedAt When the count was made.
 * @param now When it is read.
 * @param clock Locale and time zone, the viewer's when left out.
 * @example
 * refreshTimes(new Date('2026-11-06T14:42Z'), new Date('2026-11-06T15:00Z'), { locale: 'en-GB', timeZone: 'UTC' })
 * // { updated: '14:42', next: '15:42' }
 */
export function refreshTimes(countedAt: Date, now: Date, clock: Clock = {}) {
  const next = new Date(countedAt.getTime() + REFRESH_SECONDS * 1000)
  return {
    updated: formatTime(countedAt, now, clock),
    next: next > now ? formatTime(next, now, clock) : undefined,
  }
}
